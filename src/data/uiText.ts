import { formatHanziPair } from '@/data/ingredients'
import type { ChineseScript } from '@/types/game'

export interface MultiLangText {
  zh: string
  zhTrad: string
  pinyin?: string
  pinyinTrad?: string
  th: string
  en: string
}

export function getCnText(entry: MultiLangText, script: ChineseScript): string {
  return formatHanziPair(entry.zh, entry.zhTrad, script)
}

export function formatInlineLabel(
  entry: MultiLangText,
  script: ChineseScript,
  showThai: boolean,
  showEnglish: boolean
): string {
  const parts = [getCnText(entry, script)]
  if (showThai) parts.push(entry.th)
  if (showEnglish) parts.push(entry.en)
  return parts.join(' · ')
}

